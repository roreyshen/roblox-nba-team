#!/usr/bin/env python3
"""Generate tests/mock/generated.luau for the mock Roblox harness.

Usage: python3 tests/mock/gen.py <Full-API-Dump.json> [studio fonts dir]

Contents:
  API    - every class: superclass, creatable, and members (property type/readonly, events, methods)
  ENUMS  - every enum and its items
  FONTS  - font families shipped with Studio (so Font.new paths can be checked)
  TREE   - the Rojo project tree with each script's source code
"""
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
api_path = sys.argv[1]
fonts_dir = sys.argv[2] if len(sys.argv) > 2 else "/Applications/RobloxStudio.app/Contents/Resources/content/fonts/families"


def lua_str(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif o < 32 or o == 127:
            out.append("\\%03d" % o)
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def long_str(s):
    eq = "="
    while ("]" + eq + "]") in s:
        eq += "="
    return "[" + eq + "[\n" + s + "]" + eq + "]"


api = json.load(open(api_path))
out = ["-- GENERATED by tests/mock/gen.py. Do not edit.", "local API = {}"]

for c in api["Classes"]:
    tags = c.get("Tags") or []
    members = []
    for m in c["Members"]:
        mtags = [t for t in (m.get("Tags") or []) if isinstance(t, str)]
        kind = m["MemberType"]
        name = m["Name"]
        if kind == "Property":
            vt = m["ValueType"]
            sec = m.get("Security")
            write_sec = sec.get("Write") if isinstance(sec, dict) else sec
            read_sec = sec.get("Read") if isinstance(sec, dict) else sec
            ro = "ReadOnly" in mtags or "NotScriptable" in mtags or write_sec not in (None, "None")
            hidden = "NotScriptable" in mtags or read_sec not in (None, "None")
            default = m.get("Default")
            members.append(
                "[%s]={k=\"P\",t=%s,ro=%s,hid=%s,d=%s}"
                % (lua_str(name), lua_str(vt["Category"] + ":" + vt["Name"]), str(ro).lower(), str(hidden).lower(),
                   lua_str(default) if isinstance(default, str) else "nil")
            )
        elif kind == "Event":
            members.append("[%s]={k=\"E\"}" % lua_str(name))
        elif kind == "Function":
            members.append("[%s]={k=\"F\"}" % lua_str(name))
        elif kind == "Callback":
            members.append("[%s]={k=\"C\"}" % lua_str(name))
    out.append(
        "API[%s]={super=%s,creatable=%s,service=%s,members={%s}}"
        % (lua_str(c["Name"]), lua_str(c["Superclass"]) if c["Superclass"] != "<<<ROOT>>>" else "nil",
           str("NotCreatable" not in tags).lower(), str("Service" in tags).lower(), ",".join(members))
    )

out.append("local ENUMS = {}")
for e in api["Enums"]:
    items = ",".join("[%s]=%d" % (lua_str(i["Name"]), i["Value"]) for i in e["Items"])
    out.append("ENUMS[%s]={%s}" % (lua_str(e["Name"]), items))

out.append("local FONTS = {}")
for f in sorted(os.listdir(fonts_dir)):
    if f.endswith(".json"):
        faces = json.load(open(os.path.join(fonts_dir, f)))["faces"]
        weights = sorted({face["weight"] for face in faces})
        out.append("FONTS[%s]={%s}" % (lua_str(f[:-5]), ",".join("[%d]=true" % w for w in weights)))

# Project tree with sources (rojo sourcemap includes every instance and its file).
sm = json.loads(subprocess.check_output(
    ["rojo", "sourcemap", "--include-non-scripts", os.path.join(ROOT, "default.project.json")], cwd=ROOT))


def node(n):
    parts = ["name=%s" % lua_str(n["name"]), "className=%s" % lua_str(n["className"])]
    for fp in n.get("filePaths") or []:
        if fp.endswith(".luau") or fp.endswith(".lua"):
            parts.append("source=%s" % long_str(open(os.path.join(ROOT, fp)).read()))
            parts.append("path=%s" % lua_str(fp))
    kids = [node(c) for c in n.get("children") or []]
    parts.append("children={%s}" % ",".join(kids))
    return "{" + ",".join(parts) + "}"


out.append("local TREE = " + node(sm))
out.append("return { API = API, ENUMS = ENUMS, FONTS = FONTS, TREE = TREE }")

dest = os.path.join(ROOT, "tests", "mock", "generated.luau")
open(dest, "w").write("\n".join(out) + "\n")
print("wrote", dest, os.path.getsize(dest) // 1024, "KB")
